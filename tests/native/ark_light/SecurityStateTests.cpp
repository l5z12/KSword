// S-08: Actual configuration list
// ---------------------------------------------------------------------------
void testSupportClaim(ksword_tests::Suite& s) {
    // Empty claim list = BLOCKED.
    {
        const SupportClaim kClaim = evaluateSupportClaim({});
        s.expect(kClaim.status == SupportClaimStatus::kBlocked,
                 L"S-08 with no verified configuration the claim stays BLOCKED");
        s.expect(!kClaim.baselineConfigurationVerified && !kClaim.vbsConfigurationVerified,
                 L"S-08 an empty inventory verifies nothing");
        s.expect(hasKey(kClaim.limitationKeys, security_limitation_keys::kSupportClaimBlocked),
                 L"S-08 BLOCKED is accounted for explicitly");
    }

    VerifiedConfiguration baseline;
    baseline.configurationId = "baseline";
    baseline.osBuildRaw = "10.0.26300.9022";
    baseline.vbsRunning = TriState::kNo;
    baseline.hvciRunning = TriState::kNo;
    baseline.kswordDriverLoaded = TriState::kYes;
    baseline.evidenceFieldId = "env.baseline";

    VerifiedConfiguration hardened;
    hardened.configurationId = "vbs-hvci";
    hardened.osBuildRaw = "10.0.26100.1742";
    hardened.vbsRunning = TriState::kYes;
    hardened.hvciRunning = TriState::kYes;
    hardened.kswordDriverLoaded = TriState::kNo;
    hardened.evidenceFieldId = "env.hardened";

    // Only one set: PartiallyVerified.
    {
        const SupportClaim kClaim = evaluateSupportClaim({baseline});
        s.expect(kClaim.status == SupportClaimStatus::kPartiallyVerified,
                 L"S-08 one configuration only is partially verified");
        s.expect(kClaim.baselineConfigurationVerified && !kClaim.vbsConfigurationVerified,
                 L"S-08 only the configuration actually checked counts");
        s.expect(hasKey(kClaim.limitationKeys, security_limitation_keys::kSupportClaimIncomplete),
                 L"S-08 partial verification is accounted for explicitly");
    }

    // Both sets complete: Verified.
    {
        const SupportClaim kClaim = evaluateSupportClaim({baseline, hardened});
        s.expect(kClaim.status == SupportClaimStatus::kVerified,
                 L"S-08 both configurations present makes the claim verified");
        s.expect(kClaim.acceptedConfigurationIds.size() == 2U, L"S-08 both configurations are accepted");
        s.expect(kClaim.rejectedConfigurationIds.empty(), L"S-08 no configuration is rejected");
    }

    // Missing build: invalid.
    {
        VerifiedConfiguration noBuild = baseline;
        noBuild.osBuildRaw.clear();
        const SupportClaim kClaim = evaluateSupportClaim({noBuild, hardened});
        s.expect(kClaim.status == SupportClaimStatus::kPartiallyVerified,
                 L"S-08 a configuration without a recorded build does not count");
        s.expect(kClaim.rejectedConfigurationIds.size() == 1U,
                 L"S-08 the configuration missing a build is rejected");
        s.expect(!kClaim.baselineConfigurationVerified,
                 L"S-08 without a build the baseline is not verified");
    }

    // Missing driver load state: invalid.
    {
        VerifiedConfiguration noDriver = baseline;
        noDriver.kswordDriverLoaded = TriState::kUnknown;
        const SupportClaim kClaim = evaluateSupportClaim({noDriver, hardened});
        s.expect(!kClaim.baselineConfigurationVerified,
                 L"S-08 a configuration without a recorded driver state does not count");
    }

    // VBS enabled but HVCI status unknown: invalid.
    {
        VerifiedConfiguration vague = hardened;
        vague.hvciRunning = TriState::kUnknown;
        const SupportClaim kClaim = evaluateSupportClaim({baseline, vague});
        s.expect(!kClaim.vbsConfigurationVerified,
                 L"S-08 an unknown HVCI state disqualifies the VBS configuration");
        s.expect(kClaim.status == SupportClaimStatus::kPartiallyVerified,
                 L"S-08 only the baseline left means partially verified");
        s.expect(kClaim.acceptedConfigurationIds.size() == 1U,
                 L"S-08 the vague configuration is not listed as accepted");
    }
}

// ---------------------------------------------------------------------------
// S-01: Summary logic for the fourth dimension at the capability level. The summary **must** consist only of states that
// have actually been returned; synthesizing an Error that no one ever returned flattens "requires admin" into "broken".
// ---------------------------------------------------------------------------
void testCapabilityOutcomeSummary(ksword_tests::Suite& s) {
    // Expected values are manually calculated: both assertions fail, and AccessDenied is the highest
    // severity among them, with its original WIN32 5 / 'Access is denied.' message bubbling up unchanged.
    const auto kBuildTwoFieldCapability = [](const SecurityField& a, const SecurityField& b) {
        SecurityStateInput input;
        input.currentWindow = currentWindow();
        input.fields = {a, b};
        input.claims = {
            makeClaim(SecurityCapabilityId::kCredentialGuard, SecurityDimension::kConfigured,
                      TriState::kNo, a.fieldId.c_str()),
            makeClaim(SecurityCapabilityId::kCredentialGuard, SecurityDimension::kRunning,
                      TriState::kNo, b.fieldId.c_str()),
        };
        return evaluateSecurityState(input);
    };

    SecurityField denied = makeField("cg.wmi", "wmi", kBootCurrent);
    denied.outcome =
        CollectionOutcome::failure(CollectionStatus::kAccessDenied, "WIN32", 5U, "Access is denied.");
    SecurityField unsupported = makeField("cg.reg", "registry", kBootCurrent);
    unsupported.outcome = CollectionOutcome::failure(CollectionStatus::kUnsupported, "HRESULT",
                                                     0x80041010ULL, "Invalid class");

    // (a) AccessDenied + Unsupported。
    {
        const SecurityStateReport kReport = kBuildTwoFieldCapability(denied, unsupported);
        const CapabilityState* cg = kReport.findCapability(SecurityCapabilityId::kCredentialGuard);
        s.expect(cg != nullptr && cg->queryOutcome.status != CollectionStatus::kSuccess,
                 L"S-01 a capability whose every query was denied never summarises as Success");
        s.expect(cg != nullptr && cg->queryOutcome.status != CollectionStatus::kPartial,
                 L"S-01 a capability with no observation at all never summarises as Partial");
        s.expect(cg != nullptr && cg->queryOutcome.status != CollectionStatus::kError,
                 L"S-01 the summary never invents an Error status no source returned");
        s.expect(cg != nullptr && cg->queryOutcome.status == CollectionStatus::kAccessDenied,
                 L"S-01 a privilege failure stays recognisable at the capability level");
        s.expect(cg != nullptr && cg->queryOutcome.nativeCode == OptionalU64::of(5U) &&
                     cg->queryOutcome.nativeCodeDomain == "WIN32",
                 L"S-01 the summarised failure keeps its own native code and domain");
        s.expect(cg != nullptr && cg->queryOutcome.message == "Access is denied.",
                 L"S-01 the summarised failure keeps the source message");
        s.expect(kReport.hasLimitation(security_limitation_keys::kOutcomeMixedFailures),
                 L"S-01 summarising away the other failure statuses is accounted for explicitly");
        s.expect(cg != nullptr && cg->configured.value == TriState::kUnknown &&
                     cg->running.value == TriState::kUnknown,
                 L"S-01 CredentialGuard stays Unknown when every supporting query failed");
        s.expect(cg != nullptr && !cg->anyBackedObservation,
                 L"S-01 a capability whose fields all failed carries no backed observation");
    }

    // (a') The conclusion must remain the same regardless of order — the summary is not determined by the first entry.
    {
        const SecurityStateReport kReport = kBuildTwoFieldCapability(unsupported, denied);
        const CapabilityState* cg = kReport.findCapability(SecurityCapabilityId::kCredentialGuard);
        s.expect(cg != nullptr && cg->queryOutcome.status == CollectionStatus::kAccessDenied,
                 L"S-01 the summarised failure does not depend on which field came first");
        s.expect(cg != nullptr && cg->queryOutcome.nativeCode == OptionalU64::of(5U),
                 L"S-01 the summarised native code does not depend on field order either");
    }

    // (b) AccessDenied + Timeout。
    {
        SecurityField timeout = makeField("cg.reg", "registry", kBootCurrent);
        timeout.outcome = CollectionOutcome::failure(CollectionStatus::kTimeout, "WIN32", 1460U,
                                                     "The operation timed out.");
        const SecurityStateReport kReport = kBuildTwoFieldCapability(denied, timeout);
        const CapabilityState* cg = kReport.findCapability(SecurityCapabilityId::kCredentialGuard);
        s.expect(cg != nullptr && cg->queryOutcome.status == CollectionStatus::kAccessDenied,
                 L"S-01 a timeout alongside a denial does not hide the denial");
        s.expect(cg != nullptr && cg->queryOutcome.nativeCode == OptionalU64::of(5U),
                 L"S-01 the denial native code survives the timeout");
    }

    // (c) Two cases both have AccessDenied but different error codes: the status is preserved, but the error
    //     code is left blank. Picking one of the two real error codes as a 'representative' is misleading.
    {
        SecurityField deniedOther = makeField("cg.reg", "registry", kBootCurrent);
        deniedOther.outcome = CollectionOutcome::failure(CollectionStatus::kAccessDenied, "WIN32",
                                                         1314U, "A required privilege is not held.");
        const SecurityStateReport kReport = kBuildTwoFieldCapability(denied, deniedOther);
        const CapabilityState* cg = kReport.findCapability(SecurityCapabilityId::kCredentialGuard);
        s.expect(cg != nullptr && cg->queryOutcome.status == CollectionStatus::kAccessDenied,
                 L"S-01 two denials with different codes still summarise as AccessDenied");
        s.expect(cg != nullptr && !cg->queryOutcome.nativeCode.present,
                 L"S-01 two different native codes do not get a made up representative code");
        s.expect(!kReport.hasLimitation(security_limitation_keys::kOutcomeMixedFailures),
                 L"S-01 same-status failures are not reported as mixed failure statuses");
    }

    // (d) Partial must not be swallowed by Success: an incomplete collection coverage renders the entire capability coverage incomplete.
    {
        SecurityField full = makeField("cg.wmi", "wmi", kBootCurrent);
        full.raw = rawNumber("1", 1U);
        SecurityField partial = makeField("cg.reg", "registry", kBootCurrent);
        partial.outcome.status = CollectionStatus::kPartial;
        const SecurityStateReport kReport = kBuildTwoFieldCapability(full, partial);
        const CapabilityState* cg = kReport.findCapability(SecurityCapabilityId::kCredentialGuard);
        s.expect(cg != nullptr && cg->queryOutcome.status == CollectionStatus::kPartial,
                 L"S-01 one partial query makes the whole capability outcome Partial");
        s.expect(cg != nullptr && cg->queryOutcome.status != CollectionStatus::kSuccess,
                 L"S-01 a partial query is never rounded up to Success");
    }

    // (e) NotCollected means 'not run', not 'run failed'. These must be tracked separately in the ledger.
    {
        SecurityStateInput input;
        input.currentWindow = currentWindow();
        SecurityField never = makeField("cg.never", "wmi", kBootCurrent);
        never.outcome = CollectionOutcome::notCollected();
        input.fields = {never};
        input.claims = {makeClaim(SecurityCapabilityId::kCredentialGuard, SecurityDimension::kRunning,
                                  TriState::kYes, "cg.never")};
        const SecurityStateReport kReport = evaluateSecurityState(input);
        s.expect(kReport.envelope.coverage.succeeded == 0U,
                 L"S-01 a field that never ran covers nothing");
        s.expect(kReport.envelope.coverage.failed == 0U,
                 L"S-01 a field that never ran is not counted as a failed query");
        s.expect(kReport.envelope.coverage.skipped == 1U,
                 L"S-01 a field that never ran is accounted as skipped");

        SecurityStateInput failedInput = input;
        failedInput.fields[0].outcome = CollectionOutcome::failure(CollectionStatus::kError,
                                                                   "NTSTATUS", 0xC0000001ULL,
                                                                   "STATUS_UNSUCCESSFUL");
        const SecurityStateReport kFailedReport = evaluateSecurityState(failedInput);
        s.expect(kFailedReport.envelope.coverage.failed == 1U &&
                     kFailedReport.envelope.coverage.skipped == 0U,
                 L"S-01 a query that ran and failed is accounted as failed, not as skipped");
    }
}

// ---------------------------------------------------------------------------
// S-02: Reference ambiguity for duplicate fieldId. The same input must not yield different conclusions when reordered.
// ---------------------------------------------------------------------------
void testDuplicateFieldResolution(ksword_tests::Suite& s) {
    SecurityField bad = makeField("dg.state", "wmi", kBootCurrent);
    bad.outcome =
        CollectionOutcome::failure(CollectionStatus::kAccessDenied, "WIN32", 5U, "Access is denied.");
    SecurityField good = makeField("dg.state", "registry", kBootCurrent);
    good.raw = rawNumber("2", 2U);

    const auto kEvaluate = [&bad, &good](bool badFirst) {
        SecurityStateInput input;
        input.currentWindow = currentWindow();
        if (badFirst) {
            input.fields = {bad, good};
        } else {
            input.fields = {good, bad};
        }
        input.claims = {makeClaim(SecurityCapabilityId::kHypervisorEnforcedCodeIntegrity,
                                  SecurityDimension::kRunning, TriState::kYes, "dg.state")};
        return evaluateSecurityState(input);
    };

    const SecurityStateReport kBadFirst = kEvaluate(true);
    const SecurityStateReport kGoodFirst = kEvaluate(false);
    const CapabilityState* a =
        kBadFirst.findCapability(SecurityCapabilityId::kHypervisorEnforcedCodeIntegrity);
    const CapabilityState* b =
        kGoodFirst.findCapability(SecurityCapabilityId::kHypervisorEnforcedCodeIntegrity);

    s.expect(a != nullptr && b != nullptr && a->running.value == b->running.value,
             L"S-02 a duplicate field id yields the same verdict whichever copy comes first");
    s.expect(a != nullptr && a->running.value == TriState::kUnknown,
             L"S-02 a claim over an ambiguous field id produces no value");
    s.expect(b != nullptr && b->running.value == TriState::kUnknown,
             L"S-02 the reversed order does not resolve the ambiguity into a definite value");
    s.expect(a != nullptr && a->running.claims.size() == 1U && !a->running.claims[0].backed,
             L"S-02 a claim over an ambiguous field id is treated as unbacked");
    s.expect(a != nullptr && a->running.claims[0].sourceGroup.empty(),
             L"S-02 an ambiguous claim is not attributed to a collector that may not have supplied it");
    s.expect(kBadFirst.hasLimitation(security_limitation_keys::kFieldDuplicateId) &&
                 kGoodFirst.hasLimitation(security_limitation_keys::kFieldDuplicateId),
             L"S-02 the duplicate id is reported in both orderings");
    s.expect(kBadFirst.hasLimitation(security_limitation_keys::kClaimUnbacked),
             L"S-02 a claim left unbacked by an ambiguous id is accounted for explicitly");
    s.expect(kBadFirst.fields.size() == 2U && kGoodFirst.fields.size() == 2U,
             L"S-02 both copies of the duplicated field are still listed");
}

// ---------------------------------------------------------------------------
// S-05 / F-11: Independent source counting. The N in 'N independent sources agree' must not be falsely reported.
// ---------------------------------------------------------------------------
void testSourceGroupCounting(ksword_tests::Suite& s) {
    // Two queries from the same source group are treated as a single source, not two.
    {
        SecurityStateInput input;
        input.currentWindow = currentWindow();
        SecurityField classA = makeField("dg.wmi.a", "wmi", kBootCurrent);
        classA.raw = rawNumber("2", 2U);
        SecurityField classB = makeField("dg.wmi.b", "wmi", kBootCurrent);
        classB.raw = rawNumber("2", 2U);
        input.fields = {classA, classB};
        input.claims = {
            makeClaim(SecurityCapabilityId::kHypervisorEnforcedCodeIntegrity,
                      SecurityDimension::kConfigured, TriState::kYes, "dg.wmi.a"),
            makeClaim(SecurityCapabilityId::kHypervisorEnforcedCodeIntegrity,
                      SecurityDimension::kConfigured, TriState::kYes, "dg.wmi.b"),
        };
        const SecurityStateReport kReport = evaluateSecurityState(input);
        const CapabilityState* hvci =
            kReport.findCapability(SecurityCapabilityId::kHypervisorEnforcedCodeIntegrity);
        s.expect(hvci != nullptr && hvci->configured.definiteClaimCount == 2U,
                 L"S-05 two queries from one source group are still two claims");
        s.expect(hvci != nullptr && hvci->configured.distinctSourceGroupCount == 1U,
                 L"S-05 two queries from one source group count as one independent source");
        s.expect(hvci != nullptr && hvci->configured.value == TriState::kYes,
                 L"S-05 two agreeing claims from one group still yield that value");
    }

    // Three different groups correspond to three items.
    {
        SecurityStateInput input;
        input.currentWindow = currentWindow();
        SecurityField wmi = makeField("dg.wmi", "wmi", kBootCurrent);
        wmi.raw = rawNumber("2", 2U);
        SecurityField registry = makeField("dg.registry", "registry", kBootCurrent);
        registry.raw = rawNumber("1", 1U);
        SecurityField runtime = makeField("dg.runtime", "runtime", kBootCurrent);
        runtime.raw = rawText("present");
        input.fields = {wmi, registry, runtime};
        input.claims = {
            makeClaim(SecurityCapabilityId::kHypervisorEnforcedCodeIntegrity,
                      SecurityDimension::kConfigured, TriState::kYes, "dg.wmi"),
            makeClaim(SecurityCapabilityId::kHypervisorEnforcedCodeIntegrity,
                      SecurityDimension::kConfigured, TriState::kYes, "dg.registry"),
            makeClaim(SecurityCapabilityId::kHypervisorEnforcedCodeIntegrity,
                      SecurityDimension::kConfigured, TriState::kYes, "dg.runtime"),
        };
        const SecurityStateReport kReport = evaluateSecurityState(input);
        const CapabilityState* hvci =
            kReport.findCapability(SecurityCapabilityId::kHypervisorEnforcedCodeIntegrity);
        s.expect(hvci != nullptr && hvci->configured.distinctSourceGroupCount == 3U,
                 L"S-05 three distinct source groups count as three independent sources");
        s.expect(hvci != nullptr && hvci->configured.definiteClaimCount == 3U,
                 L"S-05 all three agreeing claims took part");
    }

    // Two unsigned evidence items count as two, not one; otherwise, an empty grouping key would merge them into a phantom source.
    {
        SecurityStateInput input;
        input.currentWindow = currentWindow();
        SecurityField first;
        first.fieldId = "anon.one";
        first.window.bootId = kBootCurrent;
        first.window.machineId = kMachine;
        first.outcome = CollectionOutcome::success();
        first.raw = rawText("yes");
        SecurityField second = first;
        second.fieldId = "anon.two";
        second.raw = rawText("no");
        input.fields = {first, second};
        input.claims = {
            makeClaim(SecurityCapabilityId::kSecureBoot, SecurityDimension::kRunning, TriState::kYes,
                      "anon.one"),
            makeClaim(SecurityCapabilityId::kSecureBoot, SecurityDimension::kRunning, TriState::kNo,
                      "anon.two"),
        };
        const SecurityStateReport kReport = evaluateSecurityState(input);
        const CapabilityState* sb = kReport.findCapability(SecurityCapabilityId::kSecureBoot);
        s.expect(sb != nullptr && sb->running.conflicted,
                 L"S-05 two unattributed sources disagreeing is still a conflict");
        s.expect(sb != nullptr && sb->running.definiteClaimCount == 2U,
                 L"S-05 both unattributed claims took part");
        s.expect(sb != nullptr && sb->running.distinctSourceGroupCount == 2U,
                 L"S-05 two unattributed sources are two sources, not one merged phantom group");
        s.expect(kReport.hasLimitation(security_limitation_keys::kSourceGroupUnattributed),
                 L"S-05 an unattributed source is accounted for explicitly");
    }
}

// ---------------------------------------------------------------------------
// S-05: Sources prior to reboot can also conflict; this must be visible.
// ---------------------------------------------------------------------------
void testHistoricalConflict(ksword_tests::Suite& s) {
    SecurityField wmi = makeField("hvci.old.wmi", "wmi", kBootPrevious);
    wmi.raw = rawNumber("2", 2U);
    SecurityField registry = makeField("hvci.old.registry", "registry", kBootPrevious);
    registry.raw = rawNumber("0", 0U);

    SecurityStateInput input;
    input.currentWindow = currentWindow();
    input.fields = {wmi, registry};
    input.claims = {
        makeClaim(SecurityCapabilityId::kHypervisorEnforcedCodeIntegrity, SecurityDimension::kRunning,
                  TriState::kYes, "hvci.old.wmi"),
        makeClaim(SecurityCapabilityId::kHypervisorEnforcedCodeIntegrity, SecurityDimension::kRunning,
                  TriState::kNo, "hvci.old.registry"),
    };

    const SecurityStateReport kReport = evaluateSecurityState(input);
    const CapabilityState* hvci =
        kReport.findCapability(SecurityCapabilityId::kHypervisorEnforcedCodeIntegrity);
    s.expect(hvci != nullptr && hvci->running.value == TriState::kUnknown,
             L"S-02 pre-reboot sources never set the present value");
    s.expect(hvci != nullptr && hvci->running.definiteClaimCount == 0U,
             L"S-02 pre-reboot claims do not take part in the present value");
    s.expect(hvci != nullptr && hvci->running.historicalValue == TriState::kUnknown,
             L"S-05 two disagreeing pre-reboot sources do not arbitrate into one historical value");
    s.expect(hvci != nullptr && hvci->running.historicalConflicted,
             L"S-05 the pre-reboot disagreement is flagged instead of vanishing into Unknown");
    s.expect(kReport.hasLimitation(security_limitation_keys::kHistoricalConflict),
             L"S-05 a pre-reboot disagreement is accounted for explicitly");
    const DimensionConflict* conflict = kReport.findConflict(
        SecurityCapabilityId::kHypervisorEnforcedCodeIntegrity, SecurityDimension::kRunning);
    s.expect(conflict != nullptr, L"S-05 a pre-reboot disagreement reaches the conflict table");
    s.expect(conflict != nullptr && conflict->historicalConflict && !conflict->currentConflict,
             L"S-05 the conflict table says the disagreement is pre-reboot, not current");
    s.expect(conflict != nullptr && conflict->claims.size() == 2U &&
                 conflict->claims[0].value == TriState::kYes &&
                 conflict->claims[1].value == TriState::kNo,
             L"S-05 both pre-reboot source values are shown side by side");
    s.expect(conflict != nullptr && conflict->resolvedValue == TriState::kUnknown,
             L"S-05 a pre-reboot conflict picks no value for the caller either");
    s.expect(kReport.conclusion == AnalysisConclusion::kDifferenceObserved,
             L"S-05 disagreeing pre-reboot sources are a difference, not a clean run");

    // Reference: When two historical sources agree, there is no conflict, and the value still goes into historicalValue.
    {
        SecurityStateInput agree = input;
        agree.claims[1].value = TriState::kYes;
        const SecurityStateReport kAgreeReport = evaluateSecurityState(agree);
        const CapabilityState* agreeHvci =
            kAgreeReport.findCapability(SecurityCapabilityId::kHypervisorEnforcedCodeIntegrity);
        s.expect(agreeHvci != nullptr && !agreeHvci->running.historicalConflicted,
                 L"S-05 two agreeing pre-reboot sources are not a conflict");
        s.expect(agreeHvci != nullptr && agreeHvci->running.historicalValue == TriState::kYes,
                 L"S-05 two agreeing pre-reboot sources yield that historical value");
        s.expect(agreeHvci != nullptr && agreeHvci->running.value == TriState::kUnknown,
                 L"S-02 agreeing pre-reboot sources still do not set the present value");
        s.expect(kAgreeReport.conflicts.empty(),
                 L"S-05 agreeing pre-reboot sources leave the conflict table empty");
    }
}

// ---------------------------------------------------------------------------
// S-07: Administrator and System are two distinct tiers.
// ---------------------------------------------------------------------------
void testPrivilegeTiers(ksword_tests::Suite& s) {
    SecurityStateInput input;
    input.currentWindow = currentWindow();
    input.privilege.administrator = TriState::kYes;   // Already administrator
    input.privilege.system = TriState::kUnknown;      // But no SYSTEM/TCB.
    input.privilege.kswordDriverLoaded = TriState::kNo;

    SecurityField systemField = makeField("f.system", "r0", kBootCurrent);
    systemField.outcome = CollectionOutcome::notCollected();
    systemField.access = AccessRequirement::kSystem;

    SecurityField adminField = makeField("f.admin", "reg", kBootCurrent);
    adminField.outcome = CollectionOutcome::notCollected();
    adminField.access = AccessRequirement::kAdministrator;

    SecurityField driverField = makeField("f.driver", "r0", kBootCurrent);
    driverField.outcome = CollectionOutcome::notCollected();
    driverField.access = AccessRequirement::kKswordDriver;

    SecurityField plainField = makeField("f.plain", "reg", kBootCurrent);
    plainField.outcome = CollectionOutcome::notCollected();
    plainField.access = AccessRequirement::kNone;

    input.fields = {systemField, adminField, driverField, plainField};
    input.claims = {makeClaim(SecurityCapabilityId::kTestSigning, SecurityDimension::kRunning,
                              TriState::kNo, "f.system")};

    const SecurityStateReport kReport = evaluateSecurityState(input);
    const FieldAssessment* systemView = kReport.findField("f.system");
    const FieldAssessment* adminView = kReport.findField("f.admin");
    s.expect(systemView != nullptr &&
                 systemView->availability == FieldAvailability::kBlockedByPrivilege,
             L"S-07 a SYSTEM level field with only administrator present is a privilege block");
    s.expect(adminView != nullptr && adminView->availability == FieldAvailability::kNotCollected,
             L"S-07 an administrator level field with administrator present is merely not collected");
    s.expect(systemView != nullptr && adminView != nullptr &&
                 systemView->availability != adminView->availability,
             L"S-07 the System tier and the Administrator tier do not resolve identically");
    const FieldAssessment* driverView = kReport.findField("f.driver");
    const FieldAssessment* plainView = kReport.findField("f.plain");
    s.expect(driverView != nullptr && driverView->availability == FieldAvailability::kBlockedByDriver,
             L"S-07 the driver tier stays its own availability value");
    s.expect(plainView != nullptr && plainView->availability == FieldAvailability::kNotCollected,
             L"S-07 a field needing no privilege is merely not collected");
    s.expect(kReport.blockedFieldCount == 2U,
             L"S-07 exactly the SYSTEM field and the driver field count as blocked");
    s.expect(kReport.hasLimitation(security_limitation_keys::kSystemPrivilegeDegraded),
             L"S-07 a missing SYSTEM tier is reported on its own limitation key");
    s.expect(!kReport.hasLimitation(security_limitation_keys::kPrivilegeDegraded),
             L"S-07 with administrator present no administrator degradation is reported");

    const CapabilityState* testSigning = kReport.findCapability(SecurityCapabilityId::kTestSigning);
    s.expect(testSigning != nullptr && testSigning->requiresSystem,
             L"S-07 a capability backed by a SYSTEM level field is labelled as needing SYSTEM");
    s.expect(testSigning != nullptr && !testSigning->requiresAdministrator,
             L"S-07 a SYSTEM requirement is not folded into an administrator requirement");

    // Once SYSTEM is obtained, the same field simply indicates 'not running'.
    {
        SecurityStateInput elevated = input;
        elevated.privilege.system = TriState::kYes;
        const SecurityStateReport kElevatedReport = evaluateSecurityState(elevated);
        const FieldAssessment* elevatedSystem = kElevatedReport.findField("f.system");
        s.expect(elevatedSystem != nullptr &&
                     elevatedSystem->availability == FieldAvailability::kNotCollected,
                 L"S-07 with SYSTEM present the SYSTEM field is no longer a privilege block");
        s.expect(!kElevatedReport.hasLimitation(security_limitation_keys::kSystemPrivilegeDegraded),
                 L"S-07 with SYSTEM present no SYSTEM degradation is reported");
        s.expect(kElevatedReport.blockedFieldCount == 1U,
                 L"S-07 only the driver field stays blocked once SYSTEM is present");
    }

    // Reverse case: the administrator profile reports a downgrade only when administrator privileges are absent, and it does not impersonate the SYSTEM profile.
    {
        SecurityStateInput unprivileged = input;
        unprivileged.privilege.administrator = TriState::kNo;
        const SecurityStateReport kUnprivilegedReport = evaluateSecurityState(unprivileged);
        const FieldAssessment* view = kUnprivilegedReport.findField("f.admin");
        s.expect(view != nullptr && view->availability == FieldAvailability::kBlockedByPrivilege,
                 L"S-07 without administrator the administrator field is a privilege block");
        s.expect(kUnprivilegedReport.hasLimitation(security_limitation_keys::kPrivilegeDegraded) &&
                     kUnprivilegedReport.hasLimitation(
                         security_limitation_keys::kSystemPrivilegeDegraded),
                 L"S-07 the two missing tiers are reported on two separate keys");
    }
}

// ---------------------------------------------------------------------------
// S-01: anyBackedObservation is a public output; all four cases must be strictly enforced.
// ---------------------------------------------------------------------------
void testBackedObservationFlag(ksword_tests::Suite& s) {
    // Actual observation
    {
        SecurityStateInput input;
        input.currentWindow = currentWindow();
        SecurityField field = makeField("sb.enabled", "uefi", kBootCurrent);
        field.raw = rawText("True");
        input.fields = {field};
        input.claims = {makeClaim(SecurityCapabilityId::kSecureBoot, SecurityDimension::kRunning,
                                  TriState::kYes, "sb.enabled")};
        const SecurityStateReport kReport = evaluateSecurityState(input);
        const CapabilityState* sb = kReport.findCapability(SecurityCapabilityId::kSecureBoot);
        s.expect(sb != nullptr && sb->anyBackedObservation,
                 L"S-01 a capability with an observed backing field reports a backed observation");
    }

    // Assert that no field is referenced.
    {
        SecurityStateInput input;
        input.currentWindow = currentWindow();
        input.claims = {makeClaim(SecurityCapabilityId::kSecureBoot, SecurityDimension::kRunning,
                                  TriState::kYes, "nowhere")};
        const SecurityStateReport kReport = evaluateSecurityState(input);
        const CapabilityState* sb = kReport.findCapability(SecurityCapabilityId::kSecureBoot);
        s.expect(sb != nullptr && !sb->anyBackedObservation,
                 L"S-01 an unbacked claim does not count as a backed observation");
    }

    // Field exists, but the query failed.
    {
        SecurityStateInput input;
        input.currentWindow = currentWindow();
        SecurityField field = makeField("sb.enabled", "uefi", kBootCurrent);
        field.outcome = CollectionOutcome::failure(CollectionStatus::kAccessDenied, "WIN32", 5U,
                                                   "Access is denied.");
        input.fields = {field};
        input.claims = {makeClaim(SecurityCapabilityId::kSecureBoot, SecurityDimension::kRunning,
                                  TriState::kYes, "sb.enabled")};
        const SecurityStateReport kReport = evaluateSecurityState(input);
        const CapabilityState* sb = kReport.findCapability(SecurityCapabilityId::kSecureBoot);
        s.expect(sb != nullptr && sb->anyClaim && !sb->anyBackedObservation,
                 L"S-01 a claim over a failed field is a claim but not a backed observation");
    }

    // Capability for complete absence in a round.
    {
        SecurityStateInput input;
        input.currentWindow = currentWindow();
        input.requestedCapabilities = {SecurityCapabilityId::kTpmReadiness};
        const SecurityStateReport kReport = evaluateSecurityState(input);
        const CapabilityState* tpm = kReport.findCapability(SecurityCapabilityId::kTpmReadiness);
        s.expect(tpm != nullptr && !tpm->anyBackedObservation,
                 L"S-01 a capability absent for the whole run has no backed observation");
    }

    // Historical observations count as 'actual observations' but do not represent the current value.
    {
        SecurityStateInput input;
        input.currentWindow = currentWindow();
        SecurityField field = makeField("sb.enabled", "uefi", kBootPrevious);
        field.raw = rawText("True");
        input.fields = {field};
        input.claims = {makeClaim(SecurityCapabilityId::kSecureBoot, SecurityDimension::kRunning,
                                  TriState::kYes, "sb.enabled")};
        const SecurityStateReport kReport = evaluateSecurityState(input);
        const CapabilityState* sb = kReport.findCapability(SecurityCapabilityId::kSecureBoot);
        s.expect(sb != nullptr && sb->anyBackedObservation && sb->running.value == TriState::kUnknown,
                 L"S-01 a pre-reboot observation is a backed observation without being the present value");
    }
}

// ---------------------------------------------------------------------------
// S-01 / S-04: Walk through the complete pipeline for the specified capabilities in the specification, not just a single slot in the enumeration.
// ---------------------------------------------------------------------------
void testNamedCapabilitiesEndToEnd(ksword_tests::Suite& s) {
    SecurityStateInput input;
    input.currentWindow = currentWindow();

    SecurityField configured = makeField("dg.servicesConfigured", "wmi", kBootCurrent);
    configured.raw = rawNumber("1", 1U);
    SecurityField running = makeField("dg.servicesRunning", "wmi", kBootCurrent);
    running.raw = rawNumber("0", 0U);
    SecurityField userMode = makeField("ci.userMode", "wmi", kBootCurrent);
    userMode.raw = rawNumber("2", 2U);
    SecurityField secureLaunch = makeField("sgsl.capable", "wmi", kBootCurrent);
    secureLaunch.raw = rawText("False");

    input.fields = {configured, running, userMode, secureLaunch};
    // Asserted values are all handwritten literals, not produced by Interpret*.
    input.claims = {
        makeClaim(SecurityCapabilityId::kCredentialGuard, SecurityDimension::kConfigured,
                  TriState::kYes, "dg.servicesConfigured"),
        makeClaim(SecurityCapabilityId::kCredentialGuard, SecurityDimension::kRunning, TriState::kNo,
                  "dg.servicesRunning"),
        makeClaim(SecurityCapabilityId::kUserModeCodeIntegrityPolicy, SecurityDimension::kRunning,
                  TriState::kYes, "ci.userMode"),
        makeClaim(SecurityCapabilityId::kSystemGuardSecureLaunch,
                  SecurityDimension::kHardwareSupport, TriState::kNo, "sgsl.capable"),
    };
    input.requestedCapabilities = {SecurityCapabilityId::kCredentialGuard,
                                   SecurityCapabilityId::kUserModeCodeIntegrityPolicy,
                                   SecurityCapabilityId::kSystemGuardSecureLaunch,
                                   SecurityCapabilityId::kKernelDmaProtection};

    const SecurityStateReport kReport = evaluateSecurityState(input);

    const CapabilityState* cg = kReport.findCapability(SecurityCapabilityId::kCredentialGuard);
    s.expect(cg != nullptr && cg->configured.value == TriState::kYes,
             L"S-01 Credential Guard configured comes from the configured property");
    s.expect(cg != nullptr && cg->running.value == TriState::kNo,
             L"S-01 Credential Guard configured is never reused as running");
    s.expect(cg != nullptr && cg->hardwareSupport.value == TriState::kUnknown,
             L"S-01 Credential Guard hardware support is not inferred from its configuration");
    s.expect(cg != nullptr && cg->anyBackedObservation && cg->queryOutcome.status ==
                                                              CollectionStatus::kSuccess,
             L"S-01 Credential Guard records that both of its queries succeeded");

    const CapabilityState* umci =
        kReport.findCapability(SecurityCapabilityId::kUserModeCodeIntegrityPolicy);
    s.expect(umci != nullptr && umci->running.value == TriState::kYes,
             L"S-04 the user mode code integrity policy has its own capability state");
    s.expect(umci != nullptr && umci->configured.value == TriState::kUnknown,
             L"S-04 a running user mode policy does not imply a configured one");

    const CapabilityState* sgsl =
        kReport.findCapability(SecurityCapabilityId::kSystemGuardSecureLaunch);
    s.expect(sgsl != nullptr && sgsl->hardwareSupport.value == TriState::kNo,
             L"S-01 System Guard Secure Launch expresses its hardware support on its own");
    s.expect(sgsl != nullptr && sgsl->running.value == TriState::kUnknown,
             L"S-01 an unsupported Secure Launch does not auto-derive a running state");

    const CapabilityState* dma = kReport.findCapability(SecurityCapabilityId::kKernelDmaProtection);
    s.expect(dma != nullptr && !dma->anyClaim &&
                 dma->queryOutcome.status == CollectionStatus::kNotCollected,
             L"S-03 Kernel DMA protection was requested and reports that nothing was collected");
    s.expect(kReport.missingCapabilityCount == 1U,
             L"S-03 exactly the uncollected Kernel DMA protection counts as absent");
}

