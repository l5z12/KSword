$r = Run @('--json','status')
$st = $null
try { $st = $r.Out | ConvertFrom-Json } catch { }
Note ('status exit=' + $r.Exit + ' status bit=' + ($st.stateNames -join ' '))

# If resident mode is already running, stop it first. 'nested' and 'hidehv' are identical in status bits; reuse one from an unknown source.
# Resident: equivalent to running the entire measurement in an unselected mode and reporting the reading.
if ($st.stateNames -contains 'RESIDENT_ACTIVE') {
    $r = Run @('stop'); Note ('stop (clear the resident hypervisor whose mode is unknown) exit=' + $r.Exit)
    $r = Run @('--json','status')
    try { $st = $r.Out | ConvertFrom-Json } catch { }
}
if ($st.stateNames -contains 'FAULTED' -or $st.stateNames -contains 'ROLLBACK_REQUIRED') {
    $r = Run @('reset-fault'); Note ('reset-fault exit=' + $r.Exit)
}
if (-not ($st.stateNames -contains 'RESOURCES_READY')) {
    $r = Run @('prepare'); Note ('prepare exit=' + $r.Exit)
    $r = Run @('--json','status')
    try { $st = $r.Out | ConvertFrom-Json } catch { }
}
if (-not ($st.stateNames -contains 'SELF_TEST_PASSED')) {
    $r = Run @('self-test'); Note ('self-test exit=' + $r.Exit)
    $r = Run @('--json','status')
    try { $st = $r.Out | ConvertFrom-Json } catch { }
}
Note ('State bits before becoming resident ' + ($st.stateNames -join ' '))
$r = Run @('resident-nested-hidehv')
Note ('resident-nested-hidehv exit=' + $r.Exit)
if ($r.Exit -ne 0) { Note 'Resident hypervisor failed to start, stopping'; exit 1 }

$r = Run @('--json','cpuid-view')
Note ('cpuid-view ' + $r.Out.Trim())

$r = Run @('--json','status')
