// S-01: Tri-state and enum explanation
// ---------------------------------------------------------------------------
void testTriStateAndEnums(ksword_tests::Suite& s) {
    s.expect(std::string(triStateName(TriState::kUnknown)) == "Unknown",
             L"S-01 TriState Unknown has a name");
    s.expect(std::string(triStateName(TriState::kNo)) == "No", L"S-01 TriState No has a name");
    s.expect(std::string(triStateName(TriState::kYes)) == "Yes", L"S-01 TriState Yes has a name");
    s.expect(triStateIsDefinite(TriState::kYes) && triStateIsDefinite(TriState::kNo),
             L"S-01 Yes and No are definite values");
    s.expect(!triStateIsDefinite(TriState::kUnknown), L"S-01 Unknown is not a definite value");

    // The default construction must be Unknown; failing to assign a value should not default to 'disabled'.
    const CapabilityState kDefaultState;
    s.expect(kDefaultState.hardwareSupport.value == TriState::kUnknown &&
                 kDefaultState.configured.value == TriState::kUnknown &&
                 kDefaultState.running.value == TriState::kUnknown,
             L"S-01 a default-constructed capability has all three dimensions Unknown");
    s.expect(kDefaultState.queryOutcome.status == CollectionStatus::kNotCollected,
             L"S-01 a default queryOutcome is NotCollected, not success");

    // --- Win32_DeviceGuard service codes (known values) ---
    const DeviceGuardServiceValue kNone = interpretDeviceGuardService(rawNumber("0", 0U));
    s.expect(kNone.service == DeviceGuardService::kNone && kNone.interpretation.recognized,
             L"S-01 DeviceGuard code 0 is None");
    const DeviceGuardServiceValue kCg = interpretDeviceGuardService(rawNumber("1", 1U));
    s.expect(kCg.service == DeviceGuardService::kCredentialGuard &&
                 kCg.interpretation.normalizedName == "CredentialGuard",
             L"S-01 DeviceGuard code 1 is CredentialGuard");
    const DeviceGuardServiceValue kHvci = interpretDeviceGuardService(rawNumber("2", 2U));
    s.expect(kHvci.service == DeviceGuardService::kHypervisorEnforcedCodeIntegrity &&
                 kHvci.interpretation.normalizedName == "HypervisorEnforcedCodeIntegrity",
             L"S-01 DeviceGuard code 2 is HVCI");
    const DeviceGuardServiceValue kSbcg = interpretDeviceGuardService(rawNumber("3", 3U));
    s.expect(kSbcg.service == DeviceGuardService::kSystemGuardSecureLaunch &&
                 kSbcg.interpretation.normalizedName == "SystemGuardSecureLaunch",
             L"S-01 DeviceGuard code 3 is SystemGuardSecureLaunch");
    const DeviceGuardServiceValue kSmm = interpretDeviceGuardService(rawNumber("4", 4U));
    s.expect(kSmm.service == DeviceGuardService::kSmmFirmwareMeasurement &&
                 kSmm.interpretation.normalizedName == "SmmFirmwareMeasurement",
             L"S-01 DeviceGuard code 4 is SmmFirmwareMeasurement");

    // --- Unknown enum value: Preserve original value, leave interpretation empty, never guess
    const DeviceGuardServiceValue kFuture = interpretDeviceGuardService(rawNumber("9", 9U));
    s.expect(kFuture.service == DeviceGuardService::kUnknown,
             L"S-01 an unknown service code does not collapse into a known one");
    s.expect(!kFuture.interpretation.recognized, L"S-01 an unknown service code is flagged unrecognized");
    s.expect(kFuture.interpretation.normalizedName.empty(),
             L"S-01 an unrecognized code gets no normalized name");
    s.expect(kFuture.interpretation.rawCode == OptionalU64::of(9U),
             L"S-01 an unknown service code keeps its raw numeric value");
    s.expect(kFuture.interpretation.rawText == "9", L"S-01 an unknown service code keeps its raw text");

    const DeviceGuardServiceValue kTextual = interpretDeviceGuardService(rawText("HypervisorEnforced"));
    s.expect(!kTextual.interpretation.recognized, L"S-01 a non numeric source is not guessed at");
    s.expect(!kTextual.interpretation.rawCode.present,
             L"S-01 a non numeric source leaves rawCode unset instead of 0");
    s.expect(kTextual.interpretation.rawText == "HypervisorEnforced",
             L"S-01 a non numeric source keeps its raw text");

    // --- VBS status codes ---
    const VbsStatusValue kOff = interpretVbsStatus(rawNumber("0", 0U));
    s.expect(kOff.status == VbsStatus::kDisabled && kOff.interpretation.normalizedName == "Disabled",
             L"S-01 VBS code 0 is Disabled");
    const VbsStatusValue kConfiguredOnly = interpretVbsStatus(rawNumber("1", 1U));
    s.expect(kConfiguredOnly.status == VbsStatus::kEnabledNotRunning &&
                 kConfiguredOnly.interpretation.normalizedName == "EnabledNotRunning",
             L"S-01 VBS code 1 is EnabledNotRunning");
    const VbsStatusValue kRunningNow = interpretVbsStatus(rawNumber("2", 2U));
    s.expect(kRunningNow.status == VbsStatus::kEnabledAndRunning &&
                 kRunningNow.interpretation.normalizedName == "EnabledAndRunning",
             L"S-01 VBS code 2 is EnabledAndRunning");
    const VbsStatusValue kVbsFuture = interpretVbsStatus(rawNumber("7", 7U));
    s.expect(kVbsFuture.status == VbsStatus::kUnknown && !kVbsFuture.interpretation.recognized &&
                 kVbsFuture.interpretation.rawCode == OptionalU64::of(7U),
             L"S-01 an unknown VBS status code keeps its value and is not interpreted");

    // --- Configured and Running states must not be mixed
    TriState configured = TriState::kYes;
    TriState running = TriState::kYes;
    vbsStatusToDimensions(VbsStatus::kDisabled, configured, running);
    s.expect(configured == TriState::kNo && running == TriState::kNo,
             L"S-01 Disabled maps to configured=No and running=No");
    vbsStatusToDimensions(VbsStatus::kEnabledNotRunning, configured, running);
    s.expect(configured == TriState::kYes, L"S-01 EnabledNotRunning maps to configured=Yes");
    s.expect(running == TriState::kNo,
             L"S-01 EnabledNotRunning maps to running=No so Configured is never reused as Running");
    vbsStatusToDimensions(VbsStatus::kEnabledAndRunning, configured, running);
    s.expect(configured == TriState::kYes && running == TriState::kYes,
             L"S-01 EnabledAndRunning maps to configured=Yes and running=Yes");
    configured = TriState::kYes;
    running = TriState::kYes;
    vbsStatusToDimensions(VbsStatus::kUnknown, configured, running);
    s.expect(configured == TriState::kUnknown && running == TriState::kUnknown,
             L"S-01 an unknown status code resets both dimensions to Unknown, not to off");

    // --- Security property encoding. Values 0..8 are strictly fixed: shifting this table by one position causes four documented values to silently misalign.
    s.expect(interpretSecurityProperty(rawNumber("0", 0U)).property == SecurityProperty::kNone,
             L"S-01 security property 0 is None");
    s.expect(interpretSecurityProperty(rawNumber("1", 1U)).property ==
                 SecurityProperty::kBaseVirtualizationSupport,
             L"S-01 security property 1 is BaseVirtualizationSupport");
    s.expect(interpretSecurityProperty(rawNumber("2", 2U)).property == SecurityProperty::kSecureBoot,
             L"S-01 security property 2 is SecureBoot");
    s.expect(interpretSecurityProperty(rawNumber("3", 3U)).property == SecurityProperty::kDmaProtection,
             L"S-01 security property 3 is DmaProtection");
    s.expect(interpretSecurityProperty(rawNumber("4", 4U)).property ==
                 SecurityProperty::kSecureMemoryOverwrite,
             L"S-01 security property 4 is SecureMemoryOverwrite");
    s.expect(interpretSecurityProperty(rawNumber("5", 5U)).property == SecurityProperty::kNxProtections,
             L"S-01 security property 5 is NxProtections");
    s.expect(interpretSecurityProperty(rawNumber("6", 6U)).property ==
                 SecurityProperty::kSmmMitigations,
             L"S-01 security property 6 is SmmMitigations");
    s.expect(interpretSecurityProperty(rawNumber("7", 7U)).property ==
                 SecurityProperty::kModeBasedExecutionControl,
             L"S-01 security property 7 is ModeBasedExecutionControl");
    s.expect(interpretSecurityProperty(rawNumber("8", 8U)).property ==
                 SecurityProperty::kApicVirtualization,
             L"S-01 security property 8 is ApicVirtualization");
    const SecurityPropertyValue kPropertyFuture = interpretSecurityProperty(rawNumber("15", 15U));
    s.expect(kPropertyFuture.property == SecurityProperty::kUnknown &&
                 !kPropertyFuture.interpretation.recognized &&
                 kPropertyFuture.interpretation.rawCode == OptionalU64::of(15U),
             L"S-01 an unknown security property code keeps its raw value");

    // --- Code integrity enforcement status code ---
    s.expect(interpretCodeIntegrityEnforcement(rawNumber("0", 0U)).enforcement ==
                 CodeIntegrityEnforcement::kOff,
             L"S-04 code integrity code 0 is Off");
    s.expect(interpretCodeIntegrityEnforcement(rawNumber("1", 1U)).enforcement ==
                 CodeIntegrityEnforcement::kAudit,
             L"S-04 code integrity code 1 is Audit");
    s.expect(interpretCodeIntegrityEnforcement(rawNumber("2", 2U)).enforcement ==
                 CodeIntegrityEnforcement::kEnforced,
             L"S-04 code integrity code 2 is Enforced");
    const CodeIntegrityEnforcementValue kCiFuture = interpretCodeIntegrityEnforcement(rawNumber("5", 5U));
    s.expect(kCiFuture.enforcement == CodeIntegrityEnforcement::kUnknown &&
                 !kCiFuture.interpretation.recognized && kCiFuture.interpretation.rawText == "5",
             L"S-04 an unknown code integrity code is not read as Off");

    // --- Vocabulary itself: Every capability/permission profile/constraint class explicitly named in the specification must have a unique name; no two profiles may share the same name. ---
    s.expect(std::string(securityCapabilityName(SecurityCapabilityId::kCredentialGuard)) ==
                 "CredentialGuard",
             L"S-01 CredentialGuard is named in the capability vocabulary");
    s.expect(std::string(securityCapabilityName(SecurityCapabilityId::kSystemGuardSecureLaunch)) ==
                 "SystemGuardSecureLaunch",
             L"S-01 SystemGuardSecureLaunch is named in the capability vocabulary");
    s.expect(std::string(securityCapabilityName(SecurityCapabilityId::kKernelDmaProtection)) ==
                 "KernelDmaProtection",
             L"S-03 KernelDmaProtection is named in the capability vocabulary");
    s.expect(std::string(securityCapabilityName(SecurityCapabilityId::kKernelModeCodeIntegrityPolicy)) ==
                     "KernelModeCodeIntegrityPolicy" &&
                 std::string(securityCapabilityName(
                     SecurityCapabilityId::kUserModeCodeIntegrityPolicy)) ==
                     "UserModeCodeIntegrityPolicy",
             L"S-04 kernel mode and user mode policy are two separately named capabilities");
    s.expect(std::string(securityCapabilityName(SecurityCapabilityId::kTpmPresence)) !=
                 std::string(securityCapabilityName(SecurityCapabilityId::kTpmReadiness)),
             L"S-03 TPM presence and TPM readiness do not share one name");

    s.expect(std::string(accessRequirementName(AccessRequirement::kUnknown)) == "Unknown",
             L"S-07 an undeclared access requirement is named Unknown, not None");
    s.expect(std::string(accessRequirementName(AccessRequirement::kNone)) == "None",
             L"S-07 the None access requirement has its own name");
    s.expect(std::string(accessRequirementName(AccessRequirement::kAdministrator)) == "Administrator",
             L"S-07 the Administrator access requirement has its own name");
    s.expect(std::string(accessRequirementName(AccessRequirement::kSystem)) == "System",
             L"S-07 the System access requirement is named System and not folded into Administrator");
    s.expect(std::string(accessRequirementName(AccessRequirement::kKswordDriver)) == "KswordDriver",
             L"S-07 the driver access requirement has its own name");

    s.expect(std::string(capabilityConstraintKindName(
                 CapabilityConstraintKind::kPrivilegeInsufficient)) == "PrivilegeInsufficient",
             L"S-06 PrivilegeInsufficient is a separately named constraint kind");
    s.expect(std::string(capabilityConstraintKindName(CapabilityConstraintKind::kQueryUnavailable)) ==
                 "QueryUnavailable",
             L"S-06 QueryUnavailable is a separately named constraint kind");
    s.expect(std::string(capabilityConstraintKindName(
                 CapabilityConstraintKind::kSecurityConfiguration)) == "SecurityConfiguration",
             L"S-06 SecurityConfiguration is a separately named constraint kind");
}

