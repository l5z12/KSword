// S-07: Field-level privilege degradation (readable fields remain readable).
// ---------------------------------------------------------------------------
void testPrivilegeDegradation(ksword_tests::Suite& s) {
    SecurityStateInput input;
    input.currentWindow = currentWindow();
    input.privilege.administrator = TriState::kNo;
    input.privilege.kswordDriverLoaded = TriState::kNo;

    SecurityField publicField = makeField("vbs.status", "wmi", kBootCurrent);
    publicField.raw = rawNumber("2", 2U);
    publicField.access = AccessRequirement::kNone;

    SecurityField adminField = makeField("ci.policy", "reg", kBootCurrent);
    adminField.outcome = CollectionOutcome::notCollected();
    adminField.access = AccessRequirement::kAdministrator;

    SecurityField driverField = makeField("r0.dyndata", "r0", kBootCurrent);
    driverField.outcome = CollectionOutcome::notCollected();
    driverField.access = AccessRequirement::kKswordDriver;

    input.fields = {publicField, adminField, driverField};
    input.claims = {
        makeClaim(SecurityCapabilityId::kVirtualizationBasedSecurity, SecurityDimension::kRunning,
                  TriState::kYes, "vbs.status"),
        makeClaim(SecurityCapabilityId::kKernelModeCodeIntegrityPolicy, SecurityDimension::kConfigured,
                  TriState::kYes, "ci.policy"),
        makeClaim(SecurityCapabilityId::kTestSigning, SecurityDimension::kRunning, TriState::kNo,
                  "r0.dyndata"),
    };

    const SecurityStateReport kReport = evaluateSecurityState(input);
    s.expect(kReport.fields.size() == 3U, L"S-07 without administrator the page is not blanked out");
    s.expect(kReport.readableFieldCount == 1U, L"S-07 the readable field is still readable");
    s.expect(kReport.blockedFieldCount == 2U, L"S-07 the blocked field count is exact");

    const CapabilityState* vbs =
        kReport.findCapability(SecurityCapabilityId::kVirtualizationBasedSecurity);
    s.expect(vbs != nullptr && vbs->running.value == TriState::kYes,
             L"S-07 a capability readable without administrator still reports its state");
    s.expect(vbs != nullptr && !vbs->requiresAdministrator,
             L"S-07 a capability that needs no administrator is not mislabelled");

    const CapabilityState* ci =
        kReport.findCapability(SecurityCapabilityId::kKernelModeCodeIntegrityPolicy);
    s.expect(ci != nullptr && ci->requiresAdministrator,
             L"S-07 a capability needing administrator is labelled");
    s.expect(ci != nullptr && ci->configured.value == TriState::kUnknown,
             L"S-07 a field that could not be read produces no definite value");
    s.expect(ci != nullptr && ci->blockedFieldCount == 1U,
             L"S-07 the capability counts its blocked fields");

    const CapabilityState* testSigning = kReport.findCapability(SecurityCapabilityId::kTestSigning);
    s.expect(testSigning != nullptr && testSigning->requiresKswordDriver,
             L"S-07 a capability needing the driver is labelled separately");
    s.expect(testSigning != nullptr && !testSigning->requiresAdministrator,
             L"S-07 a driver requirement is not folded into an administrator requirement");

    // When an administrator is present, the same input no longer reports a privilege downgrade.
    {
        SecurityStateInput elevated = input;
        elevated.privilege.administrator = TriState::kYes;
        elevated.fields[1].outcome = CollectionOutcome::success();
        elevated.fields[1].raw = rawNumber("1", 1U);
        const SecurityStateReport kElevatedReport = evaluateSecurityState(elevated);
        s.expect(!kElevatedReport.hasLimitation(security_limitation_keys::kPrivilegeDegraded),
                 L"S-07 with administrator and a successful read no privilege degradation is reported");
        s.expect(kElevatedReport.readableFieldCount == 2U,
                 L"S-07 elevation makes one more field readable");
        const CapabilityState* elevatedCi =
            kElevatedReport.findCapability(SecurityCapabilityId::kKernelModeCodeIntegrityPolicy);
        s.expect(elevatedCi != nullptr && elevatedCi->configured.value == TriState::kYes,
                 L"S-07 after elevation that field yields a definite value");
        s.expect(kElevatedReport.hasLimitation(security_limitation_keys::kDriverDegraded),
                 L"S-07 the driver degradation is still reported while the driver is absent");
    }
}

