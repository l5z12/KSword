// Offline automated test for the S module (platform security state and reason explanation).
//
// Cover the IDs and their respective boundaries. This is written item-by-item because listing
// only "S-01...S-08" would be misread as a stronger claim than the assertions actually support:
//   * S-01: Full coverage: four-dimensional separation, five failure semantics, and reserved unknown enums are all covered in this file.
//   * S-02 covers only the **freshness model** (bootId / machineId determination and historical values listed separately). The half of the spec regarding
//     "storing state, reopening old sessions, and viewing them side-by-side with the current one" requires serialization, while SecurityState.{h,cpp}
//     There is no serialization here, so it is outside this file and this module's scope.
//   * S-03 covers only four items: SecureBoot presence, TPM presence, TPM readiness, and measurement log availability.
//     BitLocker and DMA remapping in "other available boot-related states" lack explanation functions;
//     KernelDmaProtection is merely a slot in the capability enumeration with no corresponding Interpret* function.
//   * S-04 covers WDAC configuration scope/effective scope separation, kernel-mode/user-mode separation, and signature/policy separation.
//   * S-05: Override structured conflict output (all sources side-by-side + resolvedValue always Unknown
//     + historical conflicts listed separately). The spec's requirement to "explain possible value ranges"
//     refers to text output; this layer produces no text, only structured facts for the UI to render.
//   * S-06 covers the constraint statement gate for 'unavailable, do not start'. Clarification: This gate applies only at this layer and
//     **has not been integrated into the production path** (aside from this test project, no other location in the repository references
//     SecurityState). The MiscDock/DisableDse message regarding 'turning off memory integrity and restarting' bypasses this layer;
//     therefore, this file cannot enforce the condition that 'disabling protection is not recommended by default across the repository'.
//   * S-07: Overrides the **field-by-field privilege downgrade model** (readability matrix, three-tier separation for Administrator/System/Driver,
//     capability-level privilege annotations). Running on a real device with a standard account belongs to the target environment layer.
//   * S-08 only covers the state model of "support declaration" itself; actual measurement records from two real environments belong to the target environment layer.
//
// Assertion labels must be ASCII: TestSupport.h's Suite writes directly to std::wcout/wcerr; under
// the default 'C' locale, non-ASCII wide characters cause the stream to enter a fail state,
// swallowing subsequent counts—the existing CrossViewTests and similar suites use the same approach.
//
// Assert principle (Q-01/Q-02):
//   * Expected values must be hardcoded literals (e.g., "EnabledNotRunning", TriState::No,
//     count 2...); never feed the function under test's output back as a reference.
//   * The production interpretation functions (interpretVbsStatus / vbsStatusToDimensions ...) are only
//     directly asserted in their own unit tests, not used to generate pipeline test inputs — otherwise, a
//     single failure would cause both to fail, turning assertions into 'reference against reference';
//   * Pipeline test cases (evaluateSecurityState) use manually crafted TriState inputs, not generated by the explanation function;
//   * Each negative criterion has an independent test case: query failure, lack of permissions, unknown enumeration, cross-startup-cycle,
//     unsupported assertion, capability absence for the entire round, three-source conflict, missing measurement logs, and valid policy not found.

