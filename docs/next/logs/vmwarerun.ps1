# Force the VMware driver to re-sample the capability MSRs.
#
# vmx86.sys caches IA32_VMX_* values when the guest boots, before our resident component existed,
# Therefore, vmware-vmx receives the **original host capabilities** (measured as 0x48b=0x065018AE, which includes VPID
# And with an unrestricted guest, configuring the VMCS according to it will inevitably hit features we haven't implemented.
# Our capability filter is not wrong; it was never queried. Restarting this driver is the only way to force it to query again.
Note '--- Restart vmx86 to resample capability MSR ---'
foreach ($svc in @('VMAuthdService','VMwareHostd','VMnetDHCP','VMware NAT Service')) {
    $s = Get-Service -Name $svc -ErrorAction SilentlyContinue
    if ($s -and $s.Status -eq 'Running') { try { Stop-Service -Name $svc -Force -ErrorAction Stop; Note ('  Stop ' + $svc) } catch { Note ('  Stop ' + $svc + ' Failed: ' + $_.Exception.Message) } }
}
foreach ($drv in @('vmx86')) {
    $r1 = & sc.exe stop $drv 2>&1
    Start-Sleep -Seconds 2
    $r2 = & sc.exe start $drv 2>&1
    $st = (Get-Service -Name $drv -ErrorAction SilentlyContinue).Status
    Note ('  ' + $drv + '  Status after reboot=' + $st)
}
foreach ($svc in @('VMAuthdService')) {
    try { Start-Service -Name $svc -ErrorAction Stop; Note ('  Starting ' + $svc) } catch { Note ('  Starting ' + $svc + ' failed: ' + $_.Exception.Message) }
}

# Clear the lock directory left over from the previous round, **but only after confirming no vmware-vmx is running**.
#
# We rely on restarting the guest each round to unload the resident component. Since VMware is hard-powered off, lock directories remain in the VM directory.
# In the next vmrun cycle, it only returns `Error: Unknown error`, while sampling continues and readings are still output,
# The `vmx process count = 0` is hidden in a single line—this entire measurement cycle is unrelated to VMware.
#
# The gate must be here: last time I printed the process count but didn't use it for the check, directly deleting a **live** one.
# Locks held by vmware-vmx. Check first, then delete.
$live = @(Get-Process -Name 'vmware-vmx' -ErrorAction SilentlyContinue)
if ($live.Count -ne 0) {
    Note ('  There are ' + $live.Count + ' vmware-vmx processes running, do not lock the directory')
} else {
    $locks = @(Get-ChildItem -LiteralPath $vmDir -Filter '*.lck' -Directory -ErrorAction SilentlyContinue)
    foreach ($lock in $locks) {
        try { [IO.Directory]::Delete($lock.FullName, $true); Note ('  Delete residual lock ' + $lock.Name) }
        catch { Note ('  Failed to delete lock ' + $lock.Name + ': ' + $_.Exception.Message) }
    }
    if ($locks.Count -eq 0) { Note '  No residual lock directories' }
}

