// Offline automated test for the HOOK patch page construction layer (shared/evidence/HookPatchCompose.h).
//
// The four functions under test share a common characteristic: **they do not report errors when calculations are wrong**. If the final page is missing one byte,
// the result manifests only as "the machine behaves strangely at some moment"; if the rel32 displacement base is off by 5, the jump lands five bytes before the
// target, where there are often still valid instructions; if the ModRM byte of FF25 is written as a different value, the instruction still decodes correctly,
// but it fetches the jump target from a non-existent address; if the out-of-bounds check uses 32-bit addition, a request with an out-of-bounds size of 4 billion
// bytes will be judged as valid. These are not errors that can be detected by "installing and running once," so they must be proven on the build machine.
//
// Assertion principle (consistent with HvmEptSwitchTests.cpp):
//   * Expected values must be **independently calculated and hardcoded**, never derived by reversing the function
//     under test — a test that derives expected values from the code under test only proves that the code equals itself.
//   * Write architecture constants as **literals**, not symbols: an equation like f(SYMBOL) == SYMBOL
//     remains true if the constant is changed to another number, so no assertion will ever trigger.
//   * Test boundaries on both sides (exactly 4096 and 4097, +0x7FFFFFFF and +0x80000000, -0x80000000 and
//     -0x80000001): Testing only one side of the boundary is equivalent to not testing the boundary at all;
//   * The check order is also a criterion: when multiple reasons hold simultaneously, the return value is
//     strictly determined by the order of checks; otherwise, swapping the two if statements would have no effect.

#include "TestSupport.h"

#include "../../../shared/evidence/HookPatchCompose.h"

#include <array>
#include <cstdint>
#include <string_view>

