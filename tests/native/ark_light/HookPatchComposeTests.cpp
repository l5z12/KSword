using Page = std::array<std::uint8_t, 4096>;

// The original page's bytes are generated by an expression unrelated to the code under test; the test recalculates the same expression to verify the expected value.
// The step 31 is coprime with 256, so no segment within the full 4096-byte page is constant;
// 'missing a segment' or 'copying with an offset error' can both alter the result.
Page makeOriginal(const std::uint8_t seed) {
    Page page{};
    for (std::uint32_t i = 0U; i < 4096U; ++i) {
        page[i] = static_cast<std::uint8_t>((i * 31U + 17U + seed) & 0xFFU);
    }
    return page;
}

std::uint8_t originalByte(const std::uint32_t index, const std::uint8_t seed) {
    return static_cast<std::uint8_t>((index * 31U + 17U + seed) & 0xFFU);
}

// Bytes outside the patch range match the original page byte-by-byte—this is the invariant for "shadow page = original page + patch".
bool outsidePatchMatchesOriginal(const ComposedPage& composed,
                                 const Page& original,
                                 const std::uint32_t offset,
                                 const std::uint32_t length) {
    for (std::uint32_t i = 0U; i < 4096U; ++i) {
        if (i >= offset && i < offset + length) {
            continue;
        }
        if (composed.bytes[i] != original[i]) {
            return false;
        }
    }
    return true;
}

bool patchLanded(const ComposedPage& composed,
                 const std::uint8_t* patch,
                 const std::uint32_t offset,
                 const std::uint32_t length) {
    for (std::uint32_t i = 0U; i < length; ++i) {
        if (composed.bytes[offset + i] != patch[i]) {
            return false;
        }
    }
    return true;
}

bool allZero(const std::uint8_t* bytes, const std::uint32_t length) {
    for (std::uint32_t i = 0U; i < length; ++i) {
        if (bytes[i] != 0U) {
            return false;
        }
    }
    return true;
}

// Read the encoded 4-byte displacement as a signed integer in little-endian order. Test this step with a standalone implementation without
// borrowing any code from the unit under test; otherwise, 'encoding errors' and 'decoding errors' would cancel each other out and pass the test.
std::int32_t readDisplacement(const std::array<std::uint8_t, 5>& bytes) {
    const std::uint32_t kRaw = static_cast<std::uint32_t>(bytes[1]) |
                              (static_cast<std::uint32_t>(bytes[2]) << 8U) |
                              (static_cast<std::uint32_t>(bytes[3]) << 16U) |
                              (static_cast<std::uint32_t>(bytes[4]) << 24U);
    return static_cast<std::int32_t>(kRaw);
}

std::uint64_t readAbsoluteTarget(const std::array<std::uint8_t, 14>& bytes) {
    std::uint64_t value = 0ULL;
    for (std::uint32_t i = 0U; i < 8U; ++i) {
        value |= static_cast<std::uint64_t>(bytes[6U + i]) << (i * 8U);
    }
    return value;
}

// Reverse-engineer the target from the given displacement: target = src + 5 + delta (modulo 2^64). The fixture uses this to
// construct samples, while the function under test walks back using subtraction; the two paths do not borrow from each other.
std::uint64_t targetForDisplacement(const std::uint64_t srcVa, const std::int64_t delta) {
    return srcVa + 5ULL + static_cast<std::uint64_t>(delta);
}

// ---------------------------------------------------------------------------
// Architectural and protocol constants: write literals, not symbols.
// ---------------------------------------------------------------------------
void testArchitecturalLiterals(ksword_tests::Suite& s) {
    // A single view covers exactly one page. This value also represents the shadow byte count required by addView under
    // the Explicit seed (KvmControl.cpp:1142-1150); reducing it by one will cause the driver to reject every installation.
    s.expect(kPatchPageBytes == 4096U, L"the patch page is exactly 4096 bytes");
    // E9 rel32 instruction length. Writing 4 shifts the displacement base forward by one byte, causing the
    // jump to land one byte before the target—where it usually still decodes without immediate machine error.
    s.expect(kRel32JumpLength == 5U, L"a near jump is exactly 5 bytes");
    // FF /4 + ModRM + disp32 + 8-byte target = 14 bytes.
    s.expect(kAbsoluteJumpLength == 14U, L"an absolute jump is exactly 14 bytes");

    // Variable names 'near'/'far' are not used: the two corresponding names in Windows headers are empty macros;
    // including any additional header in this chain later would cause this file to fail compilation unexpectedly.
    const Rel32Jump kShortJump = encodeRel32Jump(0x1000ULL, 0x1005ULL);
    // The primary opcode for JMP rel32 is 0xE9 (SDM Vol.2A, JMP). 0xEB is rel8, with a different encoding length.
    s.expect(kShortJump.bytes[0] == 0xE9U, L"the near jump opcode is literally 0xE9");

    const auto kLongJump = encodeAbsoluteJump(0ULL);
    // FF /4 is JMP r/m64.
    s.expect(kLongJump[0] == 0xFFU, L"the absolute jump opcode is literally 0xFF");
    // ModRM 0x25 = mod 00 / reg 100 / rm 101. In 64-bit mode, mod=00 and rm=101 indicate RIP-relative
    // addressing; writing 0x24 (rm=100) would switch to SIB addressing, and writing 0x2C would replace the
    // reg field, turning it into a non-JMP instruction. All three encodings remain valid instructions.
    s.expect(kLongJump[1] == 0x25U, L"the absolute jump ModRM byte is literally 0x25");

    s.expect(ComposedPage{}.bytes.size() == 4096U, L"the composed page array holds 4096 bytes");
    s.expect(Rel32Jump{}.bytes.size() == 5U, L"the near jump array holds 5 bytes");
    s.expect(kLongJump.size() == 14U, L"the absolute jump array holds 14 bytes");
}

