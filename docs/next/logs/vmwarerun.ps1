# Tail of the event loop; read in two calls.
#
# The previous version read in batches of 64 lines, up to 200 batches, spawning a new process for each batch—on a guest that is 50 times slower.
# That was a few minutes ago. We only need the last segment: first query the latest sequence number, then read once from 'latest minus N'.
Note '--- End of Event Ring ---'
$r = Run @('--json','events','0')
$head = $null
try { $head = $r.Out | ConvertFrom-Json } catch { }
if ($head -eq $null) {
    Note ('events header read failed exit=' + $r.Exit)
} else {
    $newest = [int64]$head.newestSequence
    $from = [Math]::Max(0, $newest - 400)
    Note ('newestSequence=' + $newest + ' available=' + $head.availableRows + ' dropped=' + $head.droppedRows + ' read from ' + $from + ' onward')
    $r = Run @('--json','events',"$from")
    [IO.File]::WriteAllText('C:\ksword\events.json', $r.Out)
    $ev = $null
    try { $ev = $r.Out | ConvertFrom-Json } catch { }
    if ($ev -ne $null) {
        Note ('Retrieving ' + $ev.returnedRows + ' rows')
        # Log only the specific rows to be processed in this round; leave the rest in events.json.
        foreach ($row in $ev.rows) {
            $rid = $row.ruleId
            if ($rid -eq $null) { continue }
            # This CLI's numeric fields may or may not have a 0x prefix; both formats must be recognized: those with the prefix
            # This is the only approach that correctly interprets '243' as decimal rather than 0x243 when the input is hexadecimal or lacks a prefix.
            $txt = ([string]$rid).Trim()
            if ($txt -match '^0[xX]') {
                $id = [Convert]::ToInt64($txt.Substring(2), 16)
            } else {
                $id = [int64]$txt
            }
            if ($id -lt 0xF3 -or $id -gt 0xF9) { continue }
            Note ('  rule=0x' + ('{0:X2}' -f $id) +
                ' reason=' + $row.exitReason +
                ' qual=' + $row.qualification +
                ' gpa=' + $row.guestPhysicalAddress +
                ' gla=' + $row.guestLinearAddress +
                ' rip=' + $row.guestRip +
                ' status=' + $row.status +
                ' cpu=' + $row.access)
        }
    } else {
        Note ('events tail read failed exit=' + $r.Exit)
    }
}
Note '=== Done ==='
