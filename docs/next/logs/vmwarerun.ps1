# Running in guest: start hidden mode resident -> take baseline -> launch VMware VM -> collect readings.
#
# Append to C:\ksword\vmwarerun.log and close the handle immediately at each step; the last entry remains when the entire machine hangs.
# Logs are the scene of the crime — failure on this line results in a BSOD, which wipes the memory buffers.
$log = 'C:\ksword\vmwarerun.log'
function Note($s) {
    $line = ('[{0:HH:mm:ss}] {1}' -f (Get-Date), $s)
    [IO.File]::AppendAllText($log, $line + [Environment]::NewLine)
}
function Run($a) {
    $o = 'C:\ksword\ro.txt'
    $e = 'C:\ksword\re.txt'
    $p = Start-Process 'C:\ksword\hvm_ctl.exe' -ArgumentList $a -NoNewWindow -Wait -PassThru -RedirectStandardOutput $o -RedirectStandardError $e
    $out = ''
    if (Test-Path $o) { $out = [IO.File]::ReadAllText($o) }
    return @{ Exit = $p.ExitCode; Out = $out }
}

[IO.File]::WriteAllText($log, '')
